// Write a WordPress eXtended RSS (WXR 1.2) file: the format of Tools > Export, and what Demo
// Importer Plus downloads from a demo's "wxr-path".
//
// Only what a starter template needs: one author, terms, and items (attachments, pages,
// wp_block patterns, nav menu items) with post meta and term assignments.

const cdata = (s) => `<![CDATA[${String(s ?? '').replace(/]]>/g, ']]]]><![CDATA[>')}]]>`;
const esc = (s) => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/**
 * @param {object} o
 * @param {string} o.title       site title
 * @param {string} o.siteUrl     base_site_url (the network / host root)
 * @param {string} o.blogUrl     base_blog_url (the demo site)
 * @param {string} o.date        'YYYY-MM-DD HH:MM:SS' used for every item
 * @param {{id:number, taxonomy:string, slug:string, name:string}[]} o.terms
 * @param {object[]} o.items     { id, type, title, slug, status, content, parent, menuOrder,
 *                                attachmentUrl, link, meta: {key: value}, terms: [{taxonomy, slug, name}] }
 */
export function writeWxr({ title, siteUrl, blogUrl, date, terms = [], items = [], author = 'admin' }) {
  const out = [];
  out.push('<?xml version="1.0" encoding="UTF-8" ?>');
  out.push('<!-- Generated by design-to-blocks (WP Travel Kit) for Demo Importer Plus. -->');
  out.push('<rss version="2.0" xmlns:excerpt="http://wordpress.org/export/1.2/excerpt/" xmlns:content="http://purl.org/rss/1.0/modules/content/" xmlns:wfw="http://wellformedweb.org/CommentAPI/" xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:wp="http://wordpress.org/export/1.2/">');
  out.push('<channel>');
  out.push(`\t<title>${esc(title)}</title>`);
  out.push(`\t<link>${esc(blogUrl)}</link>`);
  out.push('\t<description></description>');
  out.push(`\t<pubDate>${new Date(date.replace(' ', 'T') + 'Z').toUTCString().replace('GMT', '+0000')}</pubDate>`);
  out.push('\t<language>en-US</language>');
  out.push('\t<wp:wxr_version>1.2</wp:wxr_version>');
  out.push(`\t<wp:base_site_url>${esc(siteUrl)}</wp:base_site_url>`);
  out.push(`\t<wp:base_blog_url>${esc(blogUrl)}</wp:base_blog_url>`);
  out.push(`\t<wp:author><wp:author_id>1</wp:author_id><wp:author_login>${cdata(author)}</wp:author_login><wp:author_email>${cdata('admin@example.com')}</wp:author_email><wp:author_display_name>${cdata(author)}</wp:author_display_name><wp:author_first_name>${cdata('')}</wp:author_first_name><wp:author_last_name>${cdata('')}</wp:author_last_name></wp:author>`);
  for (const t of terms) {
    out.push(`\t<wp:term><wp:term_id>${t.id}</wp:term_id><wp:term_taxonomy>${cdata(t.taxonomy)}</wp:term_taxonomy><wp:term_slug>${cdata(t.slug)}</wp:term_slug><wp:term_parent>${cdata('')}</wp:term_parent><wp:term_name>${cdata(t.name)}</wp:term_name></wp:term>`);
  }
  for (const it of items) {
    const link = it.link || `${blogUrl.replace(/\/$/, '')}/?p=${it.id}`;
    out.push('\t<item>');
    out.push(`\t\t<title>${cdata(it.title)}</title>`);
    out.push(`\t\t<link>${esc(link)}</link>`);
    out.push(`\t\t<pubDate>${new Date(date.replace(' ', 'T') + 'Z').toUTCString().replace('GMT', '+0000')}</pubDate>`);
    out.push(`\t\t<dc:creator>${cdata(author)}</dc:creator>`);
    out.push(`\t\t<guid isPermaLink="false">${esc(it.attachmentUrl || `${blogUrl.replace(/\/$/, '')}/?p=${it.id}`)}</guid>`);
    out.push('\t\t<description></description>');
    out.push(`\t\t<content:encoded>${cdata(it.content || '')}</content:encoded>`);
    out.push(`\t\t<excerpt:encoded>${cdata('')}</excerpt:encoded>`);
    out.push(`\t\t<wp:post_id>${it.id}</wp:post_id>`);
    out.push(`\t\t<wp:post_date>${cdata(date)}</wp:post_date>`);
    out.push(`\t\t<wp:post_date_gmt>${cdata(date)}</wp:post_date_gmt>`);
    out.push(`\t\t<wp:post_modified>${cdata(date)}</wp:post_modified>`);
    out.push(`\t\t<wp:post_modified_gmt>${cdata(date)}</wp:post_modified_gmt>`);
    out.push(`\t\t<wp:comment_status>${cdata('closed')}</wp:comment_status>`);
    out.push(`\t\t<wp:ping_status>${cdata('closed')}</wp:ping_status>`);
    out.push(`\t\t<wp:post_name>${cdata(it.slug)}</wp:post_name>`);
    out.push(`\t\t<wp:status>${cdata(it.status || 'publish')}</wp:status>`);
    out.push(`\t\t<wp:post_parent>${it.parent || 0}</wp:post_parent>`);
    out.push(`\t\t<wp:menu_order>${it.menuOrder || 0}</wp:menu_order>`);
    out.push(`\t\t<wp:post_type>${cdata(it.type)}</wp:post_type>`);
    out.push(`\t\t<wp:post_password>${cdata('')}</wp:post_password>`);
    out.push('\t\t<wp:is_sticky>0</wp:is_sticky>');
    if (it.attachmentUrl) out.push(`\t\t<wp:attachment_url>${cdata(it.attachmentUrl)}</wp:attachment_url>`);
    for (const t of it.terms || []) out.push(`\t\t<category domain="${esc(t.taxonomy)}" nicename="${esc(t.slug)}">${cdata(t.name)}</category>`);
    for (const [k, v] of Object.entries(it.meta || {})) {
      out.push(`\t\t<wp:postmeta><wp:meta_key>${cdata(k)}</wp:meta_key><wp:meta_value>${cdata(v)}</wp:meta_value></wp:postmeta>`);
    }
    out.push('\t</item>');
  }
  out.push('</channel>');
  out.push('</rss>');
  return out.join('\n') + '\n';
}

/**
 * Pull the terms and items out of another WXR file (for example an export of the sample trips),
 * so they can be added to the package. Returns raw XML strings; ids are kept as they are.
 */
export function extractWxrParts(xml) {
  const grab = (re) => [...xml.matchAll(re)].map((m) => m[0]);
  return {
    terms: [
      ...grab(/<wp:category>[\s\S]*?<\/wp:category>/g),
      ...grab(/<wp:tag>[\s\S]*?<\/wp:tag>/g),
      ...grab(/<wp:term>[\s\S]*?<\/wp:term>/g),
    ],
    items: grab(/<item>[\s\S]*?<\/item>/g),
    ids: [...xml.matchAll(/<wp:post_id>(\d+)<\/wp:post_id>/g)].map((m) => Number(m[1])),
    termIds: [...xml.matchAll(/<wp:term_id>(\d+)<\/wp:term_id>/g)].map((m) => Number(m[1])),
  };
}
