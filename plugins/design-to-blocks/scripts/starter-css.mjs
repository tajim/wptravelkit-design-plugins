// Build the Additional CSS of a starter template.
//
// Usage: node starter-css.mjs [--out .d2b/starter/additional.css] [--no-prune] [--parent-css <travelscape>/assets/css/blocks.css]
//
// A starter template runs on the Travelscape parent alone, so the component CSS that a child
// theme keeps in style.css goes into the site's Additional CSS instead (Demo Importer Plus
// imports it from the "custom-css" key of the Customizer data). This script puts it together:
//
//   1. the component CSS of the child-theme template (style.css from "Components used by ..."
//      down; the header and footer rules are for block template parts, which starters do not
//      use), renamed for this project like scaffold-child.mjs does: class prefix, colors, font
//   2. the template's WP Travel Engine CSS, re-scoped: in a child theme the parent adds
//      is-style-<key> to the WPTE blocks; on the parent alone it cannot, so starter pages wrap
//      each WPTE block in a Group with the class <prefix>-wpte-trips, <prefix>-wpte-search or
//      <prefix>-wpte-terms, and the rules hang off that class
//   3. .d2b/starter/custom.css: the project's own components (written in stage 4)
//
// then keeps only the rules whose <prefix>-* and ts-icon--* classes appear in .d2b/out/*.txt.
// Reads "theme" from .d2b/project.json (name, slug, classPrefix, colors, font).
import fs from 'node:fs';
import path from 'node:path';
import { argValue, readProject } from './lib/env.mjs';
import { TEMPLATE_DIR, makeRetheme } from './lib/retheme.mjs';
import { pruneCss, classesIn } from './lib/css-prune.mjs';

const project = readProject();
if (!project?.theme?.classPrefix) {
  console.error('No theme.classPrefix in .d2b/project.json. Run the interview first.');
  process.exit(2);
}
const { apply: retheme, names } = makeRetheme(project.theme);
const P = names.classPrefix;
const root = project.root;
const starterDir = path.join(root, '.d2b', 'starter');
fs.mkdirSync(starterDir, { recursive: true });

// 1. Template components.
const style = fs.readFileSync(path.join(TEMPLATE_DIR, 'style.css'), 'utf8');
const start = style.indexOf('/* -------------------------------------------------------------------------\n   Components used by');
if (start < 0) throw new Error('Template style.css: "Components used by" section not found');
const base = retheme(style.slice(start));

// 2. WPTE CSS, re-scoped from is-style-<key> to the wrapper Group's class.
const key = names.wpteStyleKey.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const wpte = ['trips', 'trip-search', 'terms'].map((f) => {
  let css = retheme(fs.readFileSync(path.join(TEMPLATE_DIR, 'assets', 'css', `${f}.css`), 'utf8'));
  css = css
    .replace(new RegExp(`\\.wp-block-wptravelengine-trips\\.is-style-${key}\\b`, 'g'), `.${P}-wpte-trips`)
    .replace(new RegExp(`\\.wp-block-wptravelengine-trip-search\\.is-style-${key}\\b`, 'g'), `.${P}-wpte-search`)
    .replace(new RegExp(`\\.wp-block-wptravelengine\\.is-style-${key}\\b`, 'g'), `.${P}-wpte-terms`);
  return css;
}).join('\n');

// 3. Project components.
const customFile = path.join(starterDir, 'custom.css');
const custom = fs.existsSync(customFile) ? fs.readFileSync(customFile, 'utf8') : '';

const all = [base, wpte, custom].join('\n');
const outDir = path.join(root, '.d2b', 'out');
const pages = fs.existsSync(outDir) ? fs.readdirSync(outDir).filter((f) => f.endsWith('.txt')) : [];
if (!pages.length && !process.argv.includes('--no-prune')) {
  console.error('No pages in .d2b/out yet: build at least one page first (or pass --no-prune).');
  process.exit(2);
}
const markup = pages.map((f) => fs.readFileSync(path.join(outDir, f), 'utf8')).join('\n');
const used = classesIn(markup);
const isManaged = (c) => c.startsWith(`${P}-`) || c.startsWith('ts-icon--');

const { css, stats } = process.argv.includes('--no-prune')
  ? { css: all, stats: { rules: '?', kept: '?' } }
  : pruneCss(all, used, isManaged);

const header = `/* ${names.name}: component CSS for the starter template pages (${pages.length} page(s)).\n   Generated by design-to-blocks starter-css.mjs. Change .d2b/starter/custom.css or the page scripts, then rebuild. */\n\n`;
const outFile = path.resolve(argValue('--out') || path.join(starterDir, 'additional.css'));
fs.writeFileSync(outFile, header + css);

// Classes the pages use that no CSS defines: usually a typo or a component whose CSS is missing.
// The parent's blocks.css defines many ts-icon--* icons: count those as defined.
const parentCss = [argValue('--parent-css'), project.parentDir && path.join(project.parentDir, 'assets', 'css', 'blocks.css')]
  .find((f) => f && fs.existsSync(f));
const defined = classesIn(all + (parentCss ? fs.readFileSync(parentCss, 'utf8') : ''));
const missing = [...used].filter((c) => isManaged(c) && !defined.has(c) && !/^ts-icon--$/.test(c));
console.log(JSON.stringify({
  file: outFile,
  bytes: Buffer.byteLength(header + css),
  rules: stats.rules,
  kept: stats.kept,
  pages,
  classesWithoutCss: missing,
  parentCss: parentCss || 'not found (set parentDir in project.json): ts-icon--* from the parent are listed as missing',
}, null, 2));
if (missing.length) {
  console.error(`WARNING: ${missing.length} class(es) used on the pages have no CSS: ${missing.join(', ')}`);
  process.exitCode = 3;
}
